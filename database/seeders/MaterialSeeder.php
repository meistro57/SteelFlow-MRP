    /**
     * Conversion factor: lbs/ft to kg/m
     */
    private const LBS_FT_TO_KG_M = 1.4882;

    /**
     * Default pricing by material type ($/lb)
     */
    private array $pricePerLb = [
        'W' => 0.75,      // Wide flange beams
        'S' => 0.75,      // Standard beams
        'C' => 0.72,      // Channels
        'MC' => 0.72,     // Misc channels
        'L' => 0.70,      // Angles
        'HSS' => 0.85,    // Hollow structural sections
        'PIPE' => 0.90,   // Pipe
        'HP' => 0.78,     // H-Piles
        'WT' => 0.76,     // Tees
        'PLATE' => 0.65,  // Plate
        'BAR' => 0.68,    // Bar stock
    ];

    /**
     * Grade assignments by material type
     */
    private array $defaultGrades = [
        'W' => 'A992',       // W-shapes per AISC
        'S' => 'A36',        // S-shapes
        'C' => 'A36',        // Channels
        'MC' => 'A36',       // Misc channels
        'L' => 'A36',        // Angles
        'HSS' => 'A500B',    // HSS tubes
        'PIPE' => 'A53B',    // Pipe
        'HP' => 'A572-50',   // H-Piles
        'WT' => 'A992',      // Tees (cut from W)
        'PLATE' => 'A36',    // Plate
        'BAR' => 'A36',      // Bar stock
    ];

    /**
     * Seed the materials table with AISC shapes and common materials.
     */
    public function run(): void
    {
        // Cache grade IDs
        $gradeIds = DB::table('grades')->pluck('id', 'code')->toArray();
        
        $sortOrder = 1;
        $totalCount = 0;

        // Seed AISC structural shapes
        foreach ($this->getAiscShapes() as $type => $shapes) {
            $gradeCode = $this->defaultGrades[$type] ?? 'A36';
            $gradeId = $gradeIds[$gradeCode] ?? $gradeIds['A36'];
            $pricePerLb = $this->pricePerLb[$type] ?? 0.75;

            foreach ($shapes as [$designation, $weightLbs]) {
                $this->insertMaterial(
                    type: $type,
                    sizeImperial: $designation,
                    sizeMetric: $this->convertToMetric($designation, $type),
                    gradeId: $gradeId,
                    weightLbs: $weightLbs,
                    pricePerLb: $pricePerLb,
                    sortOrder: $sortOrder++
                );
                $totalCount++;
            }
        }

        // Seed plate materials
        foreach ($this->getPlates() as $plate) {
            $gradeId = $gradeIds[$plate['grade']] ?? $gradeIds['A36'];
            $this->insertMaterial(
                type: 'PLATE',
                sizeImperial: $plate['size_imperial'],
                sizeMetric: $plate['size_metric'],
                gradeId: $gradeId,
                weightLbs: $plate['weight_lbs'],
                pricePerLb: $this->pricePerLb['PLATE'],
                sortOrder: $sortOrder++
            );
            $totalCount++;
        }

        // Seed flat bar materials
        foreach ($this->getFlatBars() as $bar) {
            $gradeId = $gradeIds['A36'];
            $this->insertMaterial(
                type: 'BAR',
                sizeImperial: $bar['size_imperial'],
                sizeMetric: $bar['size_metric'],
                gradeId: $gradeId,
                weightLbs: $bar['weight_lbs'],
                pricePerLb: $this->pricePerLb['BAR'],
                sortOrder: $sortOrder++
            );
            $totalCount++;
        }

        $this->command->info("Seeded {$totalCount} materials from AISC database");
    }

    /**
     * Insert a material record.
     */
    private function insertMaterial(
        string $type,
        string $sizeImperial,
        string $sizeMetric,
        int $gradeId,
        float $weightLbs,
        float $pricePerLb,
        int $sortOrder
    ): void {
        $weightKg = round($weightLbs * self::LBS_FT_TO_KG_M, 4);
        $pricePerKg = round($pricePerLb * 2.2046, 4);

        DB::table('materials')->updateOrInsert(
            [
                'type' => $type,
                'size_imperial' => $sizeImperial,
                'grade_id' => $gradeId,
            ],
            [
                'size_metric' => $sizeMetric,
                'unit_weight_lbs' => $weightLbs,
                'unit_weight_kg' => $weightKg,
                'price_per_lb' => $pricePerLb,
                'price_per_kg' => $pricePerKg,
                'surface_area_sqft' => null,
                'is_active' => true,
                'sort_order' => $sortOrder,
                'created_at' => now(),
                'updated_at' => now(),
            ]
        );
    }

    /**
     * Convert imperial designation to metric equivalent.
     */
    private function convertToMetric(string $designation, string $type): string
    {
        // For W-shapes: W12x26 -> W310x38.7 (approximate)
        if (preg_match('/^W(\d+)[xX](\d+\.?\d*)$/', $designation, $m)) {
            $depthMm = round((float)$m[1] * 25.4);
            $weightKgM = round((float)$m[2] * 1.4882, 1);
            return "W{$depthMm}x{$weightKgM}";
        }

        // For S-shapes: S12x35 -> S310x52
        if (preg_match('/^S(\d+)[xX](\d+\.?\d*)$/', $designation, $m)) {
            $depthMm = round((float)$m[1] * 25.4);
            $weightKgM = round((float)$m[2] * 1.4882, 1);
            return "S{$depthMm}x{$weightKgM}";
        }

        // For C-shapes: C12x25 -> C310x37
        if (preg_match('/^C(\d+)[xX](\d+\.?\d*)$/', $designation, $m)) {
            $depthMm = round((float)$m[1] * 25.4);
            $weightKgM = round((float)$m[2] * 1.4882, 1);
            return "C{$depthMm}x{$weightKgM}";
        }

        // For MC-shapes: MC12x35 -> MC310x52
        if (preg_match('/^MC(\d+)[xX](\d+\.?\d*)$/', $designation, $m)) {
            $depthMm = round((float)$m[1] * 25.4);
            $weightKgM = round((float)$m[2] * 1.4882, 1);
            return "MC{$depthMm}x{$weightKgM}";
        }

        // For angles: L4x4x1/2 -> L102x102x12.7
        if (preg_match('/^L([\d.]+)[xX]([\d.]+)[xX]([\d\/.-]+)$/', $designation, $m)) {
            $leg1Mm = round($this->fractionToDecimal($m[1]) * 25.4);
            $leg2Mm = round($this->fractionToDecimal($m[2]) * 25.4);
            $thickMm = round($this->fractionToDecimal($m[3]) * 25.4, 1);
            return "L{$leg1Mm}x{$leg2Mm}x{$thickMm}";
        }

        // For HSS: HSS6x6x1/4 -> HSS152x152x6.4
        if (preg_match('/^HSS([\d.]+)[xX]([\d.]+)[xX]([\d\/.-]+)$/', $designation, $m)) {
            $dim1Mm = round($this->fractionToDecimal($m[1]) * 25.4);
            $dim2Mm = round($this->fractionToDecimal($m[2]) * 25.4);
            $thickMm = round($this->fractionToDecimal($m[3]) * 25.4, 1);
            return "HSS{$dim1Mm}x{$dim2Mm}x{$thickMm}";
        }

        // For round HSS: HSS6.000x0.500 -> HSS152x12.7
        if (preg_match('/^HSS([\d.]+)[xX]([\d.]+)$/', $designation, $m)) {
            $odMm = round((float)$m[1] * 25.4);
            $thickMm = round((float)$m[2] * 25.4, 1);
            return "HSS{$odMm}x{$thickMm}";
        }

        // For Pipe: Pipe6STD -> Pipe168.3x7.1
        if (preg_match('/^Pipe(\d+)(STD|XS|XXS)$/', $designation, $m)) {
            // Approximate OD for nominal pipe sizes
            $nominalToOd = [
                '1' => 33.4, '2' => 60.3, '3' => 88.9, '4' => 114.3,
                '5' => 141.3, '6' => 168.3, '8' => 219.1, '10' => 273.0,
                '12' => 323.8, '14' => 355.6, '16' => 406.4, '18' => 457.2,
                '20' => 508.0, '24' => 609.6, '26' => 660.4, '30' => 762.0,
            ];
            $odMm = $nominalToOd[$m[1]] ?? round((float)$m[1] * 25.4);
            return "Pipe{$odMm}{$m[2]}";
        }

        // For HP: HP14x117 -> HP360x174
        if (preg_match('/^HP(\d+)[xX](\d+)$/', $designation, $m)) {
            $depthMm = round((float)$m[1] * 25.4);
            $weightKgM = round((float)$m[2] * 1.4882, 1);
            return "HP{$depthMm}x{$weightKgM}";
        }

        // For WT: WT12x52 -> WT310x77
        if (preg_match('/^WT([\d.]+)[xX]([\d.]+)$/', $designation, $m)) {
            $depthMm = round((float)$m[1] * 25.4);
            $weightKgM = round((float)$m[2] * 1.4882, 1);
            return "WT{$depthMm}x{$weightKgM}";
        }

        // Default: just return the original
        return $designation;
    }

    /**
     * Convert fraction string to decimal (e.g., "1/2" -> 0.5, "1-1/4" -> 1.25)
     */
    private function fractionToDecimal(string $value): float
    {
        // Already a decimal
        if (is_numeric($value)) {
            return (float)$value;
        }

        // Mixed number like "1-1/2"
        if (preg_match('/^(\d+)-(\d+)\/(\d+)$/', $value, $m)) {
            return (float)$m[1] + ((float)$m[2] / (float)$m[3]);
        }

        // Simple fraction like "1/2"
        if (preg_match('/^(\d+)\/(\d+)$/', $value, $m)) {
            return (float)$m[1] / (float)$m[2];
        }

        return (float)$value;
    }

